@ocr_bp.route("/status/<doc_id>", methods=["GET", "OPTIONS"])
def get_ocr_status_by_file(doc_id):
    """Get OCR-ready status for a given document ID."""
    if request.method == "OPTIONS":
        return create_options_response()

    try:
        filename = secure_filename(doc_id)
        stem = os.path.splitext(filename)[0]
        text_dir = get_data_dirs()["TEXT_DIR"]
        candidates = [
            os.path.join(text_dir, f"{stem}.txt"),
            os.path.join(text_dir, f"processed_{stem}.txt"),
            os.path.join(get_data_dirs()["OCR_DATA_DIR"], f"{stem}_ocr.json"),
        ]
        ready = any(os.path.isfile(path) for path in candidates)
        return jsonify({"filename": filename, "ocr_ready": ready})
    except Exception:
        return jsonify({"filename": doc_id, "ocr_ready": False})


def _make_bbox(points: list) -> dict:
    """Convert PaddleOCR polygon points to bbox object."""
    if not points:
        return {"x": 0, "y": 0, "width": 0, "height": 0, "points": []}
    xs = [float(p[0]) for p in points]
    ys = [float(p[1]) for p in points]
    return {
        "x": min(xs),
        "y": min(ys),
        "width": max(xs) - min(xs),
        "height": max(ys) - min(ys),
        "points": points,
    }


def _extract_json_from_llm_response(content: str) -> dict | None:
    """Try to extract JSON object from model output."""
    if not content:
        return None
    content = content.strip()
    try:
        return json.loads(content)
    except Exception:
        pass

    start = content.find("{")
    end = content.rfind("}")
    if start != -1 and end != -1 and end > start:
        candidate = content[start : end + 1]
        try:
            return json.loads(candidate)
        except Exception:
            return None
    return None


def parse_ocr_with_ollama(raw_text: str) -> dict:
    """Always attempt LLM parsing for structured OCR JSON."""
    model = os.getenv("OLLAMA_MODEL", "llama3.2")
    prompt = f"""You are an OCR post-processor.
Convert the OCR text below into STRICT JSON with this exact shape:
{{
  "derived_title": "short document title",
  "structured_units": [
    {{
      "text": "content",
      "type": "title|heading|paragraph|list_item|table_cell|footer|other"
    }}
  ],
  "full_text": "full cleaned text"
}}

Rules:
- Return ONLY valid JSON (no markdown, no explanation).
- Keep all important information from OCR text.
- If uncertain, still output best-effort JSON.

OCR text:
{raw_text}
"""
    try:
        import requests

        response = requests.post(
            "http://localhost:11434/api/generate",
            json={"model": model, "prompt": prompt, "stream": False},
            timeout=90,
        )
        if response.status_code != 200:
            return {"success": False, "error": f"Ollama returned {response.status_code}"}
        data = response.json()
        parsed = _extract_json_from_llm_response(data.get("response", ""))
        if not parsed:
            return {"success": False, "error": "LLM response was not valid JSON"}
        return {"success": True, "parsed": parsed, "model": model}
    except Exception as e:
        return {"success": False, "error": str(e)}


def _fallback_structured_units(raw_lines: list[str]) -> list[dict]:
    """Fallback unit classification when LLM JSON parse fails."""
    units = []
    for idx, line in enumerate(raw_lines):
        cleaned = line.strip()
        if not cleaned:
            continue
        line_type = "paragraph"
        if idx == 0 and len(cleaned) < 80:
            line_type = "title"
        elif cleaned.endswith(":"):
            line_type = "heading"
        elif cleaned.startswith(("-", "*", "•")):
            line_type = "list_item"
        units.append({"text": cleaned, "type": line_type})
    return units


def _perform_gemini_ocr(path: str) -> dict:
    """OCR an image or PDF through Gemini and return the same payload shape as the Paddle path."""
    from concurrent.futures import ThreadPoolExecutor
    from app.modules.ocr.gemini_ocr import ocr_image_bytes

    started = time.time()
    max_pages = int(os.environ.get("OCR_MAX_PAGES", "10"))

    pages: list[bytes] = []
    if os.path.splitext(path)[1].lower() == ".pdf":
        import fitz

        with fitz.open(path) as doc:
            for index in range(min(len(doc), max_pages)):
                pix = doc.load_page(index).get_pixmap(matrix=fitz.Matrix(2, 2))
                pages.append(pix.tobytes("png"))
    else:
        with open(path, "rb") as handle:
            pages.append(handle.read())

    if not pages:
        return {"success": False, "error": "Document has no pages"}

    with ThreadPoolExecutor(max_workers=min(4, len(pages))) as pool:
        results = list(pool.map(ocr_image_bytes, pages))

    raw_results, units, texts = [], [], []
    word_offset = 0
    width = height = 0
    for result in results:
        raw_results.extend(result["raw_results"])
        for unit in result["structured_units"]:
            units.append({**unit, "word_indices": [i + word_offset for i in unit["word_indices"]]})
        word_offset += result["word_count"]
        if result["full_text"]:
            texts.append(result["full_text"])
        page_w, page_h = result["image_dimensions"]
        width, height = max(width, page_w), max(height, page_h)

    full_text = "\n\n".join(texts)
    ocr_result = {
        "raw_results": raw_results,
        "structured_units": units,
        "full_text": full_text,
        "derived_title": next((r["derived_title"] for r in results if r["derived_title"]), ""),
        "confidence_avg": results[0]["confidence_avg"] if raw_results else 0.0,
        "word_count": word_offset,
        "timestamp": "",
        "processing_time_ms": (time.time() - started) * 1000,
        "image_dimensions": [width, height],
        "engine": "gemini",
    }
    return {
        "success": True,
        "text": full_text,
        "raw_text": full_text,
        "character_count": len(full_text),
        "line_count": len(full_text.split("\n")),
        "ocr_result": ocr_result,
        "llm": {"used": True, "success": True, "error": None, "model": os.environ.get("OCR_MODEL", "gemini")},
    }


def perform_ocr(image_path: str, language: str = "en", use_ollama: bool = True) -> dict:
    """Perform OCR and always post-process into structured JSON."""
    try:
        from app.modules.ocr.gemini_ocr import is_available as gemini_available

        if gemini_available():
            return _perform_gemini_ocr(image_path)

        from app.modules.ocr.paddle_ocr import get_ocr_processor

        started = time.time()
        processor = get_ocr_processor(get_data_dirs()["OCR_DATA_DIR"])
        raw_results = []
        page_texts = []
        image_dimensions = [0, 0]

        def _normalize_processed_result(processed: object) -> dict:
            if hasattr(processed, "to_dict"):
                return processed.to_dict()
            if isinstance(processed, dict):
                return processed
            return {}

        def _merge_page_result(page_result: dict) -> None:
            if not page_result:
                return

            for entry in page_result.get("raw_results", []) or []:
                if isinstance(entry, dict):
                    raw_results.append(entry)

            full_text = (page_result.get("full_text", "") or "").strip()
            if full_text:
                page_texts.append(full_text)

            dims = page_result.get("image_dimensions") or [0, 0]
            if isinstance(dims, (list, tuple)) and len(dims) >= 2:
                try:
                    image_dimensions[0] = max(image_dimensions[0], int(dims[0]))
                    image_dimensions[1] = max(image_dimensions[1], int(dims[1]))
                except (TypeError, ValueError):
                    pass

        # Check if PDF - convert to images first
        ext = os.path.splitext(image_path)[1].lower()

        if ext == ".pdf":
            # Convert PDF pages to images
            try:
                import fitz
                from PIL import Image
                import tempfile

                doc = fitz.open(image_path)
                try:
                    for page_num in range(len(doc)):
                        page = doc.load_page(page_num)
                        pix = page.get_pixmap(matrix=fitz.Matrix(2, 2))  # 2x zoom for better OCR
                        image_dimensions[0] = max(image_dimensions[0], pix.width)
                        image_dimensions[1] = max(image_dimensions[1], pix.height)

                        # Convert to PIL Image
                        img = Image.frombytes("RGB", [pix.width, pix.height], pix.samples)

                        # Save to temp file for OCR
                        temp_path = None
                        with tempfile.NamedTemporaryFile(suffix=".png", delete=False) as tmp:
                            img.save(tmp.name)
                            temp_path = tmp.name

                        try:
                            processed = processor.process_image(temp_path, lang=language, use_ollama=False)
                            _merge_page_result(_normalize_processed_result(processed))
                        finally:
                            if temp_path and os.path.exists(temp_path):
                                os.unlink(temp_path)
                finally:
                    doc.close()

            except ImportError:
                return {
                    "success": False,
                    "error": "PyMuPDF not available for PDF processing"
                }

        else:
            # Process image directly
            processed = processor.process_image(image_path, lang=language, use_ollama=False)
            _merge_page_result(_normalize_processed_result(processed))

        raw_text = "\n".join(page_texts).strip()
        if not raw_text and raw_results:
            raw_text = "\n".join(
                str(item.get("text", "")).strip()
                for item in raw_results
                if str(item.get("text", "")).strip()
            )

        raw_lines = [line.strip() for line in raw_text.split("\n") if line.strip()]
        llm_meta = {"used": False, "success": False, "error": None, "model": None}

        # Always attempt LLM JSON parsing when text exists.
        structured_units = []
        derived_title = raw_lines[0][:120] if raw_lines else ""
        full_text = raw_text
        if raw_text and use_ollama:
            llm_meta["used"] = True
            parsed = parse_ocr_with_ollama(raw_text)
            llm_meta["success"] = bool(parsed.get("success"))
            llm_meta["error"] = parsed.get("error")
            llm_meta["model"] = parsed.get("model")
            if parsed.get("success") and parsed.get("parsed"):
                parsed_obj = parsed["parsed"]
                structured_units = parsed_obj.get("structured_units") or []
                derived_title = (parsed_obj.get("derived_title") or derived_title)[:120]
                full_text = parsed_obj.get("full_text") or raw_text

        if not structured_units:
            structured_units = _fallback_structured_units(raw_lines)

        confidence_avg = (
            sum(float(r.get("confidence", 0)) for r in raw_results) / len(raw_results)
            if raw_results
            else 0.0
        )
        words = [w for w in full_text.replace("\n", " ").split(" ") if w.strip()]

        processing_time_ms = (time.time() - started) * 1000
        ocr_result = {
            "raw_results": raw_results,
            "structured_units": [
                {
                    "text": u.get("text", ""),
                    "type": u.get("type", "other"),
                    "bbox": u.get("bbox", {"x": 0, "y": 0, "width": 0, "height": 0}),
                    "confidence": float(u.get("confidence", confidence_avg or 0.75)),
                    "word_indices": u.get("word_indices", []),
                }
                for u in structured_units
                if isinstance(u, dict)
            ],
            "full_text": full_text,
            "derived_title": derived_title,
            "confidence_avg": confidence_avg,
            "word_count": len(words),
            "timestamp": "",
            "processing_time_ms": processing_time_ms,
            "image_dimensions": image_dimensions,
        }

        return {
            "success": True,
            "text": full_text,
            "raw_text": raw_text,
            "character_count": len(full_text),
            "line_count": len(full_text.split("\n")),
            "ocr_result": ocr_result,
            "llm": llm_meta,
        }

    except ImportError:
        return {
            "success": False,
            "error": "PaddleOCR not installed. Install with: pip install paddleocr paddlepaddle"
        }

    except Exception as e:
        return {
            "success": False,
            "error": str(e)
        }
