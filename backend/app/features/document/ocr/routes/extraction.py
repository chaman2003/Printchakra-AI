def _as_ocr_response(filename: str, result: dict) -> dict:
    """Normalize OCR payload into frontend OCRResponse shape."""
    ocr_result = result.get("ocr_result")
    success = bool(result.get("success"))
    if not isinstance(ocr_result, dict):
        text = result.get("text", "") or ""
        ocr_result = {
            "raw_results": [],
            "structured_units": [],
            "full_text": text,
            "derived_title": text.splitlines()[0][:120] if text else "",
            "confidence_avg": 0.0,
            "word_count": len([w for w in text.replace("\n", " ").split(" ") if w.strip()]),
            "timestamp": "",
            "processing_time_ms": 0,
            "image_dimensions": [0, 0],
        }

    return {
        "success": success,
        "filename": filename,
        "ocr_result": ocr_result,
        "ocr_ready": bool(ocr_result.get("word_count", 0) > 0),
        "error": result.get("error"),
    }


def _load_saved_pipeline_ocr(filename: str) -> dict | None:
    """Load OCR output generated by the 12-step phone pipeline."""
    dirs = get_data_dirs()
    stem = os.path.splitext(filename)[0]
    json_path = os.path.join(dirs["OCR_DATA_DIR"], f"{stem}_ocr.json")
    txt_candidates = [
        os.path.join(dirs["TEXT_DIR"], f"{stem}.txt"),
        os.path.join(dirs["TEXT_DIR"], f"processed_{stem}.txt"),
    ]

    saved_result = None
    if os.path.isfile(json_path):
        try:
            with open(json_path, "r", encoding="utf-8") as f:
                saved_result = json.load(f)
        except Exception as exc:
            logger.warning(f"Failed to read saved OCR JSON for {filename}: {exc}")

    text = ""
    for path in txt_candidates:
        if os.path.isfile(path):
            with open(path, "r", encoding="utf-8") as f:
                text = f.read()
            break

    if not saved_result and not text.strip():
        return None

    if not isinstance(saved_result, dict):
        saved_result = {}

    full_text = saved_result.get("full_text") or text
    raw_results = saved_result.get("raw_results") or []
    structured_units = saved_result.get("structured_units") or [
        {"text": line.strip(), "type": "paragraph"}
        for line in full_text.splitlines()
        if line.strip()
    ]
    ocr_result = {
        "raw_results": raw_results,
        "structured_units": structured_units,
        "full_text": full_text,
        "derived_title": saved_result.get("derived_title") or (full_text.splitlines()[0][:120] if full_text else ""),
        "confidence_avg": float(saved_result.get("confidence_avg", 0.0)),
        "word_count": saved_result.get("word_count")
        or len([word for word in full_text.replace("\n", " ").split(" ") if word.strip()]),
        "timestamp": saved_result.get("timestamp", ""),
        "processing_time_ms": saved_result.get("processing_time_ms", 0),
        "image_dimensions": saved_result.get("image_dimensions", [0, 0]),
        "engine": saved_result.get("engine", "enhanced_12_step"),
    }
    return {
        "success": True,
        "filename": filename,
        "ocr_result": ocr_result,
        "text": full_text,
    }


def _find_document_path(filename: str) -> str | None:
    """Resolve a document path using the app's configured storage directories."""
    dirs = get_data_dirs()
    candidate_paths = [
        os.path.join(dirs["UPLOAD_DIR"], filename),
        os.path.join(dirs["PDF_DIR"], filename),
        os.path.join(dirs["PROCESSED_DIR"], filename),
        os.path.join(dirs["CONVERTED_DIR"], filename),
    ]
    return next((path for path in candidate_paths if os.path.isfile(path)), None)


@ocr_bp.route("/extract", methods=["POST", "OPTIONS"])
def extract_text():
    """Extract text from a document using OCR."""
    if request.method == "OPTIONS":
        return create_options_response()
    
    try:
        # Handle file upload or document ID
        if "file" in request.files:
            file = request.files["file"]
            if file.filename == "":
                return jsonify({"success": False, "error": "No file selected"}), 400
            
            # Save temporarily
            import uuid
            temp_filename = f"ocr_temp_{uuid.uuid4().hex}_{secure_filename(file.filename)}"
            temp_path = os.path.join(get_data_dirs()["UPLOAD_DIR"], temp_filename)
            os.makedirs(os.path.dirname(temp_path), exist_ok=True)
            file.save(temp_path)
            document_path = temp_path
        
        else:
            data = request.get_json() or {}
            document_id = data.get("document_id")
            
            if not document_id:
                return jsonify({"success": False, "error": "No document provided"}), 400
            
            # Find document
            filename = secure_filename(document_id)
            document_path = _find_document_path(filename)
            
            if not document_path:
                return jsonify({"success": False, "error": "Document not found"}), 404
        
        # Get options
        language = request.form.get("language", "en") if "file" in request.files else (request.get_json() or {}).get("language", "en")
        use_ollama = request.form.get("use_ollama", "true").lower() == "true" if "file" in request.files else (request.get_json() or {}).get("use_ollama", True)
        
        # Perform OCR
        result = perform_ocr(document_path, language=language, use_ollama=use_ollama)
        
        if result.get("success"):
            # Save result
            ocr_results_dir = get_data_dirs()["TEXT_DIR"]
            os.makedirs(ocr_results_dir, exist_ok=True)
            
            import uuid
            result_filename = f"ocr_{uuid.uuid4().hex}.txt"
            result_path = os.path.join(ocr_results_dir, result_filename)
            
            with open(result_path, "w", encoding="utf-8") as f:
                f.write(result.get("text", ""))
            
            result["result_file"] = result_filename
            result["result_path"] = result_path
            
            logger.info(f"[OK] OCR completed for: {os.path.basename(document_path)}")
        
        response_name = os.path.basename(document_path)
        return jsonify(_as_ocr_response(response_name, result))
    
    except Exception as e:
        logger.error(f"OCR extraction error: {e}")
        return jsonify({"success": False, "error": str(e)}), 500


@ocr_bp.route("/extract/<doc_id>", methods=["GET", "OPTIONS"])
def extract_text_by_id(doc_id):
    """Extract text from a document by ID."""
    if request.method == "OPTIONS":
        return create_options_response()
    
    try:
        filename = secure_filename(doc_id)
        
        # Find document
        document_path = _find_document_path(filename)
        
        if not document_path:
            return jsonify({"success": False, "error": "Document not found"}), 404

        saved_result = _load_saved_pipeline_ocr(filename)
        if saved_result:
            return jsonify(_as_ocr_response(filename, saved_result))
        
        # Get options from query params
        language = request.args.get("language", "en")
        use_ollama = request.args.get("use_ollama", "true").lower() == "true"
        
        # Perform OCR
        result = perform_ocr(document_path, language=language, use_ollama=use_ollama)

        # Keep the result so later requests (and the file list's "has text" flag) do not re-run OCR.
        if result.get("success") and isinstance(result.get("ocr_result"), dict):
            try:
                ocr_dir = get_data_dirs()["OCR_DATA_DIR"]
                os.makedirs(ocr_dir, exist_ok=True)
                json_path = os.path.join(ocr_dir, f"{os.path.splitext(filename)[0]}_ocr.json")
                with open(json_path, "w", encoding="utf-8") as handle:
                    json.dump(result["ocr_result"], handle, ensure_ascii=True)
            except OSError as exc:
                logger.warning(f"Could not save OCR result for {filename}: {exc}")
        
        return jsonify(_as_ocr_response(filename, result))
    
    except Exception as e:
        logger.error(f"OCR extraction error: {e}")
        return jsonify({"success": False, "error": str(e)}), 500


@ocr_bp.route("/result/<result_id>", methods=["GET", "OPTIONS"])
def get_ocr_result(result_id):
    """Get OCR result by ID."""
    if request.method == "OPTIONS":
        return create_options_response()
    
    try:
        filename = secure_filename(result_id)
        result_path = os.path.join(get_data_dirs()["TEXT_DIR"], filename)
        
        if not os.path.exists(result_path):
            return jsonify({"success": False, "error": "Result not found"}), 404
        
        with open(result_path, "r", encoding="utf-8") as f:
            text = f.read()
        
        return jsonify({
            "success": True,
            "result_id": result_id,
            "text": text
        })
    
    except Exception as e:
        return jsonify({"success": False, "error": str(e)}), 500


